"""Исключения с отдельными публичным сообщением и серверной диагностикой.

Ошибки: своих не выпускает.
"""


class PublicError(Exception):
    """База ошибок сервиса, чьи параметры подключения нельзя раскрывать.

    Доменные наследники выбирают публичный текст; диагностический контекст
    хранится отдельно и используется только серверным журналом.
    """

    def __init__(self, diagnostic: str, message: str) -> None:
        super().__init__(message)
        self.diagnostic = diagnostic
