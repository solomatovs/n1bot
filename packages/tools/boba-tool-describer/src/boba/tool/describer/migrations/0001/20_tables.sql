create temporary table pg_temp.node (
    id          bigint generated by default as identity primary key,
    scope_kind  varchar not null,
    scope_id    uuid not null,
    kind        varchar not null,
    address     jsonb not null,
    url_address varchar not null,
    description varchar not null,
    s__wrt_ts   timestamptz not null default now()
);

create temporary table pg_temp.edge (
    id          bigint generated by default as identity primary key,
    source_id   bigint not null references pg_temp.node on delete cascade,
    target_id   bigint not null references pg_temp.node on delete cascade,
    kind        varchar not null,
    description varchar not null,
    s__wrt_ts   timestamptz not null default now(),
    unique (source_id, target_id, kind)
);

create unique index if not exists node_uk
    on pg_temp.node (scope_id, address);

create index if not exists node_address_gin
    on pg_temp.node using gin (address jsonb_path_ops);

create index if not exists node_kind_btree on pg_temp.node (kind);
