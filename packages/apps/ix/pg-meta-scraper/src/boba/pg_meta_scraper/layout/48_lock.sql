-- Сессионный advisory-замок на scope источника. Берётся в autocommit до begin и держится
-- через всю транзакцию 50_apply.sql, снимается 55_unlock.sql после commit или при любой
-- ошибке (или закрытием сессии). Зачем: два загрузчика одного scope иначе могут
-- разойтись. Замки for update внутри транзакции защищают только строки, которые уже
-- есть; строки, которые первый загрузчик вставил и закоммитил, второму в его
-- repeatable read снимке не видны, on conflict do nothing их молча пропускает, и второй
-- коммитит своё состояние плюс чужие невидимые строки. Замок до begin гарантирует, что
-- второй начнёт транзакцию, а значит и снимок, после коммита первого. Ожидание ограничено
-- lock_timeout сессии: занятый scope это ошибка 55P03 и повтор позже.
select
    pg_advisory_lock(
        hashtextextended(
            scheme || '://' || host || ':' || port || '/' || database, 0
        )
    ) as scope_locked
from
    raw_source;
