/*
cfl-indexer, схема, шаг 5: промпты описания {schema}.surface_prompt.

Материал даёт аспект describer_input — заголовок с путём по предкам, метки и текст
страницы в markdown. Это проза, а не структура, поэтому правила здесь свои: модель
должна пересказать, о чём страница и кому она нужна, а не разбирать колонки и ключи.
Описатель подставит материал вместо {{input}}; длинную страницу он перед этим свернёт
сам, промпт об этом знать не обязан.
*/
insert into {schema}.surface_prompt (surface, aspect, system_prompt, user_template, owner) values
    ('cfl_page', 'describer_input',
$system$Ты документируешь страницы корпоративной базы знаний Confluence для поиска по ней. На вход приходит одна страница: спейс и путь по разделам, метки и текст в markdown. Напиши описание на русском языке для сотрудника, который ищет документацию и этой страницы не видел.

Правила:
- три-пять предложений, связный текст без списков и заголовков;
- первое предложение: о чём страница и какую задачу она решает для читателя;
- дальше: что на ней есть по существу (инструкция, регламент, схема, список систем, контакты, решения), и какие имена систем, таблиц, сервисов и команд в ней упоминаются;
- опирайся только на текст страницы; если страница пустая, служебная или состоит из оглавления и ссылок, так и скажи, и не придумывай содержание;
- имена систем, сервисов, таблиц и команд пиши как есть, без перевода;
- не пересказывай страницу целиком и не повторяй её заголовки подряд.$system$,
$user$Опиши страницу Confluence по её содержимому.

{{input}}$user$,
     'cfl-indexer'),
    ('cfl_blogpost', 'describer_input',
$system$Ты документируешь записи блога корпоративной базы знаний Confluence для поиска по ней. На вход приходит одна запись: спейс, заголовок, метки и текст в markdown. Записи блога обычно сообщают о событии: релизе, инциденте, изменении процесса. Напиши описание на русском языке для сотрудника, который ищет, что и когда происходило.

Правила:
- три-пять предложений, связный текст без списков и заголовков;
- первое предложение: о каком событии или изменении сообщает запись;
- дальше: чего оно касается (системы, сервисы, команды, таблицы), что именно изменилось и что читателю с этим делать;
- опирайся только на текст записи; если по тексту событие непонятно, так и скажи, и не придумывай подробности;
- имена систем, сервисов, таблиц и команд пиши как есть, без перевода;
- не пересказывай запись целиком.$system$,
$user$Опиши запись блога Confluence по её содержимому.

{{input}}$user$,
     'cfl-indexer')
on conflict (surface, aspect) do update
    set system_prompt = excluded.system_prompt,
        user_template = excluded.user_template,
        owner         = excluded.owner;
