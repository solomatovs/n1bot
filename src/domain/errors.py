"""Базовые ошибки приложения и инфраструктурные ошибки."""
from __future__ import annotations


class AppError(Exception):
    """Базовая ошибка приложения."""


class ValidationError(AppError):
    """Обязательный параметр отсутствует или некорректен."""


# ---------------------------------------------------------------------------
# Векторное хранилище (инфраструктура)
# ---------------------------------------------------------------------------

class VectorStoreError(AppError):
    """Ошибка работы с векторным хранилищем."""


class EmbeddingConnectionError(VectorStoreError):
    """Не удалось подключиться к сервису эмбеддингов."""
